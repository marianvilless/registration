create or replace function public.is_school_admin()
returns boolean language sql stable
as $$ select coalesce(auth.jwt() -> 'app_metadata' ->> 'role' = 'admin', false) $$;

create or replace function public.default_block_for_grade(p_grade text)
returns text language sql stable
as $$
  select case trim(p_grade)
    when '9' then 'Block 3'
    when '10' then 'Block 2'
    when '11' then 'Block 5'
    when '12' then 'Block 7'
    else null
  end
$$;

create or replace function public.allocate_boarding_application()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare block record;
begin
  select b.* into block
  from public.dormitory_blocks b
  where lower(b.name) = lower(public.default_block_for_grade(coalesce(new.grade,'')))
  limit 1;

  if block.id is not null then
    if (select count(*) from public.boarding_applications a where a.allocated_block_id=block.id) < block.space_limit
       or block.space_limit = 0 then
      new.allocated_block_id := block.id;
      new.allocation_status := 'allocated';
    end
 if;
  end if;
  return new;
end;
$$;

drop trigger if exists boarding_auto_allocate on public.boarding_applications;
create trigger boarding_auto_allocate
before insert or update of grade on public.boarding_applications
for each row execute function public.allocate_boarding_application();

drop policy if exists "Admins manage blocks" on public.dormitory_blocks;
create policy "Admins manage blocks" on public.dormitory_blocks
for all to authenticated using (public.is_school_admin()) with check (public.is_school_admin());

drop policy if exists "Authenticated read blocks" on public.dormitory_blocks;
create policy "Authenticated read blocks" on public.dormitory_blocks
for select to authenticated using (true);

drop policy if exists "Student read own boarding application" on public.boarding_applications;
create policy "Student read own boarding application" on public.boarding_applications
for select to authenticated using (user_id=(select auth.uid()) or public.is_school_admin());

drop policy if exists "Student create own boarding application" on public.boarding_applications;
create policy "Student create own boarding application" on public.boarding_applications
for insert to authenticated
with check (user_id=(select auth.uid()) and not public.is_school_admin());

drop policy if exists "Student update own boarding application" on public.boarding_applications;
create policy "Student update own boarding application" on public.boarding_applications
for update to authenticated
using (user_id=(select auth.uid()) and not public.is_school_admin())
with check (user_id=(select auth.uid()) and not public.is_school_admin());

drop policy if exists "Admins update boarding applications" on public.boarding_applications;
create policy "Admins update boarding applications" on public.boarding_applications
for update to authenticated using (public.is_school_admin()) with check (public.is_school_admin());

drop policy if exists "Admins read grade defaults" on public.grade_block_defaults;
