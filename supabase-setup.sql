-- Marianville registration and boarding schema
-- Run in Supabase SQL Editor. Existing registration tables/policies are preserved.

alter table public.registrations add column if not exists submitted_at timestamptz;
alter table public.registrations add column if not exists updated_at timestamptz;

create table if not exists public.dormitory_blocks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  space_limit integer not null default 0 check (space_limit >= 0),
  room_numbers text[] not null default '{}'::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.boarding_applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade unique,
  student_id text not null,
  student_name text not null,
  grade text,
  class text,
  fee_amount numeric(12,2),
  fee_receipt_path text,
  allocated_block_id bigint references public.dormitory_blocks(id),
  room_number text,
  allocation_status text not null default 'pending' check (allocation_status in ('pending','allocated')),
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.grade_block_defaults (
  grade_key text primary key,
  block_name text not null,
  grade_label text not null,
  updated_at timestamptz not null default now()
);

